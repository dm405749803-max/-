const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'../../dist/backend-test.html'),'utf8');
const js=fs.readFileSync(path.join(__dirname,'../../dist/backend-test.js'),'utf8');
